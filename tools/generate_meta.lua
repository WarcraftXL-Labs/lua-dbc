local function parse_args(argv)
    local opts = dbd_common.parse_cli(argv, {
        positional = { "def_dir", "meta_dir" },
    })
    return {
        def_dir  = opts.positional.def_dir  or "definitions",
        meta_dir = opts.positional.meta_dir or "meta",
        builds   = opts.builds,
    }
end

-- ---------------------------------------------------------------------------
-- Main
-- ---------------------------------------------------------------------------

local function main(argv)
    local opts = parse_args(argv)
    local def_dir  = opts.def_dir
    local meta_dir = opts.meta_dir

    if not fs.isdir(def_dir) then
        cli.log(LOG, "Definitions directory '%s' not found.", def_dir)
        return
    end

    fs.mkdir(meta_dir)

    cli.log(LOG, "def_dir=%s meta_dir=%s builds=%s", def_dir, meta_dir, opts.builds)

    -- Collect JSON files from the definitions directory.
    local json_files = {}
    for _, f in ipairs(fs.listdir(def_dir, ".json")) do
        if f:sub(1, 1) ~= "_" then
            json_files[#json_files + 1] = f
        end
    end

    if #json_files == 0 then
        cli.log(LOG, "No .json file found in %s", def_dir)
        return
    end

    -- Resolve the target build list.
    local build_targets
    if opts.builds == "auto" then
        cli.log(LOG, "Discovering builds...")
        build_targets = dbd_common.discover_builds(def_dir, json_files, fs, json)
        cli.log(LOG, "%d builds found.", #build_targets)
    else
        build_targets = dbd_common.split_builds(opts.builds)
    end

    if #build_targets == 0 then
        cli.log(LOG, "No builds to process.")
        return
    end

    -- Generate per-build metadata.
    local builds_data = {}
    for _, bstr in ipairs(build_targets) do
        local btag = dbd_common.get_build_tag(bstr)
        local result = process_build(def_dir, meta_dir, json_files, bstr)
        builds_data[btag] = {
            build_str  = result.build_str,
            short_name = result.short_name,
            tables     = result.tables,
        }
    end

    -- Core library metadata (dbc, DbcTable, DbcWorkspace, RowProxy, Query).
    fs.write(fs.join(meta_dir, "_core.lua"), generate_core_meta())
    cli.log(LOG, "_core.lua written (Core library LuaLS annotations).")

    -- Shared metadata files.
    fs.write(fs.join(meta_dir, "_workspace.lua"),
        generate_workspace_meta(builds_data))
    cli.log(LOG, "_workspace.lua written.")

    fs.write(fs.join(meta_dir, "_tables.lua"),
        generate_tables_meta(builds_data))
    cli.log(LOG, "_tables.lua written.")

    local enums_dir = fs.isdir("src/dbc/enums") and "src/dbc/enums" or "src/enums"
    local enums_content, failed = generate_enums_meta(enums_dir)
    if enums_content then
        fs.write(fs.join(meta_dir, "_enums.lua"), enums_content)
        if failed and failed > 0 then
            cli.log(LOG, "_enums.lua written (%d enum files failed to load).", failed)
        else
            cli.log(LOG, "_enums.lua written.")
        end
    else
        cli.log(LOG, "_enums.lua skipped: no enums found in %s.", enums_dir)
    end

    cli.log(LOG, "Done: %d builds in '%s/'.", #build_targets, meta_dir)
end

main(arg or {})