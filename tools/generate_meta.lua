-- Maps DBDefs column types to LuaLS primitive types.
local LUA_TYPE_MAP = {
    locstring = "string",
    string    = "string",
    float     = "number",
    bool      = "boolean",
    int       = "integer",
    uint      = "integer",
}

-- Cross-platform `load` (LuaJIT provides `loadstring`; Lua 5.2+ has `load`).
local loadstring_fn = loadstring or load

-- ---------------------------------------------------------------------------
-- Small helpers
-- ---------------------------------------------------------------------------

local function pascal_case(name)
    if not name or name == "" then return "" end
    return name:sub(1, 1):upper() .. name:sub(2)
end

--- Returns a sorted list of the keys of a table.
local function sorted_keys(t)
    local keys = {}
    for k in pairs(t) do keys[#keys + 1] = k end
    table.sort(keys)
    return keys
end

