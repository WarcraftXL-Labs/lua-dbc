--- Processes all JSON definitions for one target build.
--- Writes one .lua file per table into meta/dbc/<build_tag>/.
--- Returns the list of successfully written tables plus counters.
---@param def_dir string
---@param meta_dir string
---@param json_files string[]
---@param bstr string
---@return table result { build_str, short_name, tables, skipped, errors }
local function process_build(def_dir, meta_dir, json_files, bstr)
    local timer = cli.timer()
    local btag = dbd_common.get_build_tag(bstr)
    local short_name = bstr:match("^(%d+%.%d+%.%d+)") or bstr

    local v_meta_dir = fs.join(meta_dir, "dbc", btag)
    fs.mkdir(v_meta_dir)

    local tables  = {}
    local skipped = 0
    local errors  = 0

    for _, jf in ipairs(json_files) do
        local table_name = jf:gsub("%.json$", "")

        local content = fs.read(fs.join(def_dir, jf))
        if not content then
            errors = errors + 1
            cli.log(LOG, "  [read-fail] %s", jf)
            goto continue
        end

        local ok_decode, db_def = pcall(json.decode, content)
        if not ok_decode then
            errors = errors + 1
            cli.log(LOG, "  [json-fail] %s: %s", jf, tostring(db_def))
            goto continue
        end

        local ok_gen, output = pcall(generate_table_meta,
            table_name, db_def, bstr, btag)
        if not ok_gen then
            errors = errors + 1
            cli.log(LOG, "  [gen-fail] %s: %s", jf, tostring(output))
            goto continue
        end

        if not output then
            skipped = skipped + 1
            goto continue
        end

        local out_path = fs.join(v_meta_dir, table_name .. ".lua")
        if not fs.write(out_path, output) then
            errors = errors + 1
            cli.log(LOG, "  [write-fail] %s", table_name .. ".lua")
        else
            tables[table_name] = true
        end

        ::continue::
    end

    local table_count = 0
    for _ in pairs(tables) do table_count = table_count + 1 end

    cli.log(LOG, "  %-16s %d tables, %d skipped, %d errors (%s)",
        bstr, table_count, skipped, errors, cli.format_duration(timer()))

    return {
        build_str  = bstr,
        short_name = short_name,
        tables     = tables,
        skipped    = skipped,
        errors     = errors,
    }
end

