--[[
    tools/generate_meta.lua
    Generates LuaLS (EmmyLua) annotations for lua-dbc.

    Output layout:
        meta/
        ├── _workspace.lua         # dbc.Workspace overloads + DbcWorkspace_<build>
        ├── _tables.lua            # dbc.TableName alias (all known table names)
        ├── _enums.lua             # dbc.Enums field accessors and enum classes
        └── dbc/
            └── v<tag>/
                ├── Spell.lua      # dbc.row.v335.Spell and dbc.Table.v335.Spell
                └── ...

    The enum metadata is generated by scanning src/enums/*.lua. Each enum
    file is loaded in isolation to introspect its `values` and `bits` tables,
    then a compact `---@class dbc.enums.<Name>` block is emitted.

    Usage:
        luajit tools/generate_meta.lua [definitions_dir] [meta_dir] [--builds auto|3.3.5.12340,...]
]]

