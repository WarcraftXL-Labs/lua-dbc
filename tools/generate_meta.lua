--- Loads a single enum file in isolation and returns its table.
--- Returns nil when the file is missing or fails to load.
---@param path string
---@return table|nil enum_def
---@return string|nil err
local function load_enum_file(path)
    local content = fs.read(path)
    if not content then
        return nil, "cannot read file"
    end

    local chunk, err = loadstring_fn(content, "@" .. path)
    if not chunk then
        return nil, "syntax error: " .. tostring(err)
    end

    local ok, result = pcall(chunk)
    if not ok then
        return nil, "runtime error: " .. tostring(result)
    end
    if type(result) ~= "table" then
        return nil, "module did not return a table"
    end

    return result
end

--- Emits a `---@class dbc.enums.<Name>` block for a single enum.
---@param parts table Output buffer
---@param enum_name string
---@param enum_def table
local function emit_enum_class(parts, enum_name, enum_def)
    parts[#parts + 1] = "---The " .. enum_name .. " enumeration.\n"
    parts[#parts + 1] = "---@class dbc.enums." .. enum_name .. "\n"

    if type(enum_def.values) == "table" then
        for _, k in ipairs(sorted_keys(enum_def.values)) do
            parts[#parts + 1] = "---@field " .. k .. " integer\n"
        end
    end

    if type(enum_def.bits) == "table" then
        for _, k in ipairs(sorted_keys(enum_def.bits)) do
            parts[#parts + 1] = "---@field " .. k .. " integer\n"
        end
        parts[#parts + 1] = "---@field flags table<string, integer>\n"
    end

    parts[#parts + 1] = "\n"
end

--- Generates _enums.lua by scanning src/enums/*.lua.
---@param enums_dir string
---@return string|nil content
---@return integer count
local function generate_enums_meta(enums_dir)
    if not fs.isdir(enums_dir) then
        return nil, 0
    end

    local files = fs.listdir(enums_dir, ".lua")
    if #files == 0 then
        return nil, 0
    end

    local parts = {}
    parts[#parts + 1] = "---@meta\n"
    parts[#parts + 1] = "-- Auto-generated enum stubs for LuaLS. Do not edit.\n"
    parts[#parts + 1] = "-- Generated from src/enums/*.lua\n\n"

    local enum_names = {}
    local failed = {}

    for _, jf in ipairs(files) do
        local enum_name = jf:gsub("%.lua$", "")
        local path = fs.join(enums_dir, jf)

        local enum_def, err = load_enum_file(path)
        if enum_def then
            enum_names[enum_name] = true
            emit_enum_class(parts, enum_name, enum_def)
        else
            failed[#failed + 1] = enum_name .. " (" .. tostring(err) .. ")"
        end
    end

    -- Emit the dbc.Enums registry class so `dbc.Enums.` autocompletes.
    parts[#parts + 1] = "---Registry for accessing enums by name.\n"
    parts[#parts + 1] = "---Example: dbc.Enums.ItemQuality.PURPLE\n"
    parts[#parts + 1] = "---@class dbc.Enums\n"

    for _, name in ipairs(sorted_keys(enum_names)) do
        parts[#parts + 1] = "---@field " .. name .. " dbc.enums." .. name .. "\n"
    end

    return table.concat(parts), #failed
end

