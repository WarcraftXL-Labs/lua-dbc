-- ---------------------------------------------------------------------------
-- Per-build processing
-- ---------------------------------------------------------------------------

--- Processes all JSON definitions for one target build.
--- Writes one .lua file per table into meta/dbc/<build_tag>/.
--- Returns the list of successfully written tables plus counters.
---@param def_dir string
---@param meta_dir string
---@param json_files string[]
---@param bstr string
---@return table result { build_str, short_name, tables, skipped, errors }
local function process_build(def_dir, meta_dir, json_files, bstr)
    local timer = cli.timer()
    local btag = dbd_common.get_build_tag(bstr)
    local short_name = bstr:match("^(%d+%.%d+%.%d+)") or bstr

    local v_meta_dir = fs.join(meta_dir, "dbc", btag)
    fs.mkdir(v_meta_dir)

    local tables  = {}
    local skipped = 0
    local errors  = 0

    for _, jf in ipairs(json_files) do
        local table_name = jf:gsub("%.json$", "")

        local content = fs.read(fs.join(def_dir, jf))
        if not content then
            errors = errors + 1
            cli.log(LOG, "  [read-fail] %s", jf)
            goto continue
        end

        local ok_decode, db_def = pcall(json.decode, content)
        if not ok_decode then
            errors = errors + 1
            cli.log(LOG, "  [json-fail] %s: %s", jf, tostring(db_def))
            goto continue
        end

        local ok_gen, output = pcall(generate_table_meta,
            table_name, db_def, bstr, btag)
        if not ok_gen then
            errors = errors + 1
            cli.log(LOG, "  [gen-fail] %s: %s", jf, tostring(output))
            goto continue
        end

        if not output then
            skipped = skipped + 1
            goto continue
        end

        local out_path = fs.join(v_meta_dir, table_name .. ".lua")
        if not fs.write(out_path, output) then
            errors = errors + 1
            cli.log(LOG, "  [write-fail] %s", table_name .. ".lua")
        else
            tables[table_name] = true
        end

        ::continue::
    end

    local table_count = 0
    for _ in pairs(tables) do table_count = table_count + 1 end

    cli.log(LOG, "  %-16s %d tables, %d skipped, %d errors (%s)",
        bstr, table_count, skipped, errors, cli.format_duration(timer()))

    return {
        build_str  = bstr,
        short_name = short_name,
        tables     = tables,
        skipped    = skipped,
        errors     = errors,
    }
end

-- ---------------------------------------------------------------------------
-- Argument parsing
-- ---------------------------------------------------------------------------

local function parse_args(argv)
    local opts = dbd_common.parse_cli(argv, {
        positional = { "def_dir", "meta_dir" },
    })
    return {
        def_dir  = opts.positional.def_dir  or "definitions",
        meta_dir = opts.positional.meta_dir or "meta",
        builds   = opts.builds,
    }
end

-- ---------------------------------------------------------------------------
-- Main
-- ---------------------------------------------------------------------------

local function main(argv)
    local opts = parse_args(argv)
    local def_dir  = opts.def_dir
    local meta_dir = opts.meta_dir

    cli.log(LOG, "def_dir=%s meta_dir=%s builds=%s", def_dir, meta_dir, opts.builds)

    -- Collect JSON files from the definitions directory.
    local json_files = {}
    for _, f in ipairs(fs.listdir(def_dir, ".json")) do
        if f:sub(1, 1) ~= "_" then
            json_files[#json_files + 1] = f
        end
    end

    if #json_files == 0 then
        cli.log(LOG, "No .json file found in %s", def_dir)
        return
    end

    -- Resolve the target build list.
    local build_targets
    if opts.builds == "auto" then
        cli.log(LOG, "Discovering builds...")
        build_targets = dbd_common.discover_builds(def_dir, json_files, fs, json)
        cli.log(LOG, "%d builds found.", #build_targets)
    else
        build_targets = dbd_common.split_builds(opts.builds)
    end

    if #build_targets == 0 then
        cli.log(LOG, "No builds to process.")
        return
    end

    -- Generate per-build metadata.
    local builds_data = {}
    for _, bstr in ipairs(build_targets) do
        local btag = dbd_common.get_build_tag(bstr)
        local result = process_build(def_dir, meta_dir, json_files, bstr)
        builds_data[btag] = {
            build_str  = result.build_str,
            short_name = result.short_name,
            tables     = result.tables,
        }
    end

    -- Shared metadata files.
    fs.write(fs.join(meta_dir, "_workspace.lua"),
        generate_workspace_meta(builds_data))
    cli.log(LOG, "_workspace.lua written.")

    fs.write(fs.join(meta_dir, "_tables.lua"),
        generate_tables_meta(builds_data))
    cli.log(LOG, "_tables.lua written.")

    local enums_content, failed = generate_enums_meta("src/enums")
    if enums_content then
        fs.write(fs.join(meta_dir, "_enums.lua"), enums_content)
        if failed and failed > 0 then
            cli.log(LOG, "_enums.lua written (%d enum files failed to load).", failed)
        else
            cli.log(LOG, "_enums.lua written.")
        end
    else
        cli.log(LOG, "_enums.lua skipped: no src/enums/*.lua found.")
    end

    cli.log(LOG, "Done: %d builds in '%s/'.", #build_targets, meta_dir)
end

main(arg or {})