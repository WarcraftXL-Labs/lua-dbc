--- Generates the dbc.TableName alias listing every known table.
---@param builds_data table
---@return string
local function generate_tables_meta(builds_data)
    local all_tables = {}
    for _, info in pairs(builds_data) do
        for t in pairs(info.tables) do
            all_tables[t] = true
        end
    end

    local parts = {}
    parts[#parts + 1] = "---@meta\n"
    parts[#parts + 1] = "-- Auto-generated table name aliases for LuaLS. Do not edit.\n\n"
    parts[#parts + 1] = "---Every DBC/DB2 table supported by lua-dbc.\n"
    parts[#parts + 1] = "---@alias dbc.TableName\n"

    for _, t in ipairs(sorted_keys(all_tables)) do
        parts[#parts + 1] = "---| '\"" .. t .. "\"'\n"
    end

    return table.concat(parts)
end

